/**
 * Mapping from backend audit error codes to actionable Vietnamese suggestions.
 */
export const ERROR_CODE_SUGGESTIONS: Record<string, string> = {
  AUTH_FAILED: "Sai tên đăng nhập, mật khẩu hoặc enable secret.",
  CONNECT_TIMEOUT:
    "Không kết nối được tới thiết bị (hết thời gian chờ hoặc bị từ chối). Kiểm tra IP, firewall, dịch vụ SSH.",
  CONNECT_FAILED:
    "Lỗi SSH khi kết nối (thuật toán mã hóa không tương thích, rớt kết nối…).",
  COLLECTION_FAILED:
    "Không lấy được cấu hình (thiếu quyền privileged hoặc lệnh bị từ chối).",
  COMMAND_NOT_ALLOWED: "Lệnh bị chặn bởi danh sách lệnh chỉ-đọc.",
  UNSUPPORTED_PLATFORM: "Nền tảng thiết bị chưa được hỗ trợ.",
  INTERNAL_ERROR: "Lỗi nội bộ. Xem log máy chủ.",
};

export function getErrorCodeSuggestion(code: string | null | undefined): string {
  if (!code) return "Lỗi không xác định trong quá trình audit.";
  return ERROR_CODE_SUGGESTIONS[code] || `Mã lỗi: ${code}. Vui lòng kiểm tra log hệ thống.`;
}
